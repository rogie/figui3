import {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { FIG_ICON_MANIFEST } from "../icons/manifest.js";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const ICONS_DIRECTORY = fileURLToPath(new URL("../icons/", import.meta.url));
const OUTPUT = fileURLToPath(new URL("../icons.css", import.meta.url));
const checkOnly = process.argv.includes("--check");

function fail(message) {
  throw new Error(`Icon build failed: ${message}`);
}

function listSvgFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const child = join(directory, entry.name);
    return entry.isDirectory() ? listSvgFiles(child) : [child];
  });
}

function validateManifest() {
  const names = new Set();
  let previousName = "";

  for (const icon of FIG_ICON_MANIFEST) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(icon.name)) {
      fail(`invalid icon name ${JSON.stringify(icon.name)}`);
    }
    if (names.has(icon.name)) fail(`duplicate icon name ${icon.name}`);
    if (icon.name.localeCompare(previousName) < 0) {
      fail(`manifest is not sorted: ${icon.name} follows ${previousName}`);
    }
    names.add(icon.name);
    previousName = icon.name;

    if (
      !Array.isArray(icon.sizes) ||
      icon.sizes.length === 0 ||
      icon.sizes.some((size) => !Number.isInteger(size) || size <= 0)
    ) {
      fail(`${icon.name} has invalid sizes`);
    }
    const sortedSizes = [...new Set(icon.sizes)].sort((a, b) => a - b);
    if (sortedSizes.join(",") !== icon.sizes.join(",")) {
      fail(`${icon.name} sizes must be unique and sorted`);
    }

    const componentSizes =
      typeof icon.component === "number"
        ? [icon.component]
        : icon.component
          ? [icon.component.medium, icon.component.small]
          : [];
    for (const size of componentSizes) {
      if (!icon.sizes.includes(size)) {
        fail(`${icon.name} component references missing ${size}px asset`);
      }
    }
  }
}

function validateSvg(svg, icon, size) {
  const context = `${size}/${icon.name}.svg`;
  const root = svg.match(/<svg\b([^>]*)>/i);
  if (!root) fail(`${context} has no svg root`);

  const width = root[1].match(/\bwidth=['"](\d+(?:\.\d+)?)['"]/i)?.[1];
  const height = root[1].match(/\bheight=['"](\d+(?:\.\d+)?)['"]/i)?.[1];
  if (Number(width) !== size || Number(height) !== size) {
    fail(`${context} width and height must both be ${size}`);
  }

  const viewBox = root[1]
    .match(/\bviewBox=['"]([^'"]+)['"]/i)?.[1]
    ?.trim()
    .split(/\s+/)
    .map(Number);
  if (
    !viewBox ||
    viewBox.length !== 4 ||
    viewBox.some((value) => !Number.isFinite(value)) ||
    viewBox[0] !== 0 ||
    viewBox[1] !== 0 ||
    viewBox[2] <= 0 ||
    viewBox[2] !== viewBox[3]
  ) {
    fail(`${context} must use a square viewBox starting at 0 0`);
  }

  const unsafePatterns = [
    /<script\b/i,
    /<foreignObject\b/i,
    /<image\b/i,
    /\son[a-z]+\s*=/i,
    /\b(?:href|xlink:href)\s*=/i,
    /\burl\s*\(/i,
  ];
  if (unsafePatterns.some((pattern) => pattern.test(svg))) {
    fail(`${context} contains unsupported external or executable content`);
  }
}

function encodeSvg(svg) {
  const compact = svg.trim().replace(/>\s+</g, "><");
  return encodeURIComponent(compact)
    .replace(/%20/g, " ")
    .replace(/%3D/g, "=")
    .replace(/%3A/g, ":")
    .replace(/%2F/g, "/");
}

function buildCss() {
  validateManifest();

  const expectedFiles = new Set();
  const declarations = [];
  for (const icon of FIG_ICON_MANIFEST) {
    for (const size of icon.sizes) {
      const relativePath = `icons/${size}/${icon.name}.svg`;
      const path = join(ROOT, relativePath);
      expectedFiles.add(relativePath);
      if (!existsSync(path)) fail(`missing ${relativePath}`);

      const svg = readFileSync(path, "utf8");
      validateSvg(svg, icon, size);
      declarations.push(
        `  --icon-${size}-${icon.name}: url("data:image/svg+xml,${encodeSvg(svg)}");`,
      );
    }
  }

  const actualFiles = new Set(
    listSvgFiles(ICONS_DIRECTORY)
      .filter((path) => path.endsWith(".svg"))
      .map((path) => relative(ROOT, path)),
  );
  for (const path of actualFiles) {
    if (!expectedFiles.has(path)) fail(`undeclared SVG ${path}`);
  }
  for (const path of expectedFiles) {
    if (!actualFiles.has(path)) fail(`manifest references missing ${path}`);
  }

  return `/*!
MIT License
Copyright (c) 2026 Rogie King
License: https://github.com/rogie/figui3/blob/main/LICENSE
*/
/* Generated by scripts/build-icons.mjs. Edit icons/ sources, not this file. */
@layer figui.defaults {
:root,
:host {
  /* Colorless shapes for use with mask-image */
${declarations.join("\n")}
}
}
`;
}

const css = buildCss();
if (checkOnly) {
  if (!existsSync(OUTPUT) || readFileSync(OUTPUT, "utf8") !== css) {
    fail("icons.css is stale; run npm run build:icons");
  }
  console.log(`icons.css is current (${FIG_ICON_MANIFEST.length} icons).`);
} else {
  writeFileSync(OUTPUT, css);
  console.log(`icons.css ${Buffer.byteLength(css)} bytes`);
}
