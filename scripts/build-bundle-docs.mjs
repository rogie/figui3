import { readdir, readFile, writeFile } from "node:fs/promises";

const outputPath = new URL("../BUNDLES.md", import.meta.url);
const check = process.argv.includes("--check");
const registrationPattern =
  /(?:figDefineElement|figDefineCustomizedBuiltIn|figDefineCustomElement|figEditorDefineElement|figLabDefineElement|defineElement|customElements\.define)\(\s*["']([^"']+)["']/g;

const bundles = [
  {
    name: "Core",
    imports: "`fig.css` + `fig.js`",
    includes: "Core registrations, including `fig-layer`",
    sources: ["src/core"],
  },
  {
    name: "Editor additions",
    imports: "`fig-editor.css` + `fig-editor.js`",
    includes: "Editor registrations; JavaScript also imports Core",
    sources: ["src/editor"],
  },
  {
    name: "Lab additions",
    imports: "`fig-lab.css` + `fig-lab.js`",
    includes: "Experimental registrations; JavaScript also imports Core",
    sources: ["src/lab"],
  },
];

async function sourceFiles(paths) {
  const files = [];
  const visit = async (path) => {
    const url = new URL(`../${path}`, import.meta.url);
    const entries = await readdir(url, { withFileTypes: true });
    for (const entry of entries) {
      const child = `${path}/${entry.name}`;
      if (entry.isDirectory()) {
        await visit(child);
      } else if (entry.name.endsWith(".js")) {
        files.push(child);
      }
    }
  };
  for (const path of paths) await visit(path);
  return files.sort();
}

async function registeredTags(sources) {
  const tags = new Set();
  for (const source of await sourceFiles(sources)) {
    const contents = await readFile(new URL(`../${source}`, import.meta.url), "utf8");
    for (const match of contents.matchAll(registrationPattern)) tags.add(match[1]);
  }
  return [...tags].sort();
}

const sections = [];
for (const bundle of bundles) {
  const tags = await registeredTags(bundle.sources);
  sections.push(
    `## ${bundle.name}\n\n` +
      `Import: ${bundle.imports}\n\n` +
      `${bundle.includes}. ${tags.length} registrations:\n\n` +
      tags.map((tag) => `- \`<${tag}>\``).join("\n"),
  );
}

const output =
  `<!-- Generated by scripts/build-bundle-docs.mjs. Do not edit directly. -->\n` +
  `# FigUI3 bundle registrations\n\n` +
  `This inventory is generated from the custom-element registrations in the source bundles.\n` +
  `Standalone entry points remain available for direct imports, but a tag listed under Core is\n` +
  `already registered by \`fig.js\`.\n\n` +
  sections.join("\n\n") +
  "\n";

if (check) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {}
  if (current !== output) {
    console.error("BUNDLES.md is stale. Run npm run build:bundle-docs.");
    process.exitCode = 1;
  } else {
    console.log("BUNDLES.md is current.");
  }
} else {
  await writeFile(outputPath, output);
  console.log("BUNDLES.md generated.");
}
